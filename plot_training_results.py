# Convert to numpy arrays
meta_losses = np.array(data['meta_losses'])
pre_adapt_losses = np.array(data['pre_adapt_losses'])
post_adapt_losses = np.array(data['post_adapt_losses'])
episodes = np.arange(1, len(meta_losses) + 1)

# Calculate improvements
improvements = ((pre_adapt_losses - post_adapt_losses) / pre_adapt_losses) * 100

# Create the plot
fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(12, 10))

# Plot A: Training Progress
ax1.plot(episodes, pre_adapt_losses, 'b-', label='Pre-adaptation Loss', linewidth=2)
ax1.plot(episodes, post_adapt_losses, 'r-', label='Post-adaptation Loss', linewidth=2)
ax1.plot(episodes, meta_losses, 'g--', label='Meta-loss', linewidth=2)

# Fill the improvement region
ax1.fill_between(episodes, pre_adapt_losses, post_adapt_losses, alpha=0.3, color='lightblue', label='Improvement Region')

ax1.set_xlabel('Training Episodes')
ax1.set_ylabel('Loss Value')
ax1.set_title('FOMAML Training Analysis: Pre vs Post Adaptation Performance')
ax1.legend()
ax1.grid(True, alpha=0.3)
ax1.set_xlim(1, len(episodes))

# Highlight problematic episodes
problem_episodes = episodes[meta_losses > pre_adapt_losses]
if len(problem_episodes) > 0:
    ax1.scatter(problem_episodes, meta_losses[meta_losses > pre_adapt_losses], 
               color='red', s=50, alpha=0.7, label='Meta-loss > Pre-adapt', zorder=5)

# Plot B: Improvement Rates
bars = ax2.bar(episodes, improvements, color='green', alpha=0.7, width=0.8)
ax2.set_xlabel('Training Episodes')
ax2.set_ylabel('Improvement (%)')
ax2.set_title('Per-Episode Improvement Rates')
ax2.grid(True, alpha=0.3)
ax2.set_xlim(0.5, len(episodes) + 0.5)

# Color bars based on improvement level
for i, bar in enumerate(bars):
    if improvements[i] > 10:
        bar.set_color('darkgreen')
    elif improvements[i] > 5:
        bar.set_color('green')
    else:
        bar.set_color('lightgreen')

plt.tight_layout()

# Save the plot
